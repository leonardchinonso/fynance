interface CgtPdfDocumentProps {
  report: StoredCgtReport
}

export function CgtPdfDocument({ report }: CgtPdfDocumentProps) {
  const { filters, response, generatedAt } = report
  const higherRate = report.higherRate ?? true
  const cur = response.summary.base_currency
  const footerPrefix = `Generated by fynance · ${periodLabel(filters.period)} · ${new Date(generatedAt).toLocaleString()}`
  const renderFooter = ({
    pageNumber,
    totalPages,
  }: {
    pageNumber: number
    totalPages: number
  }) => `${footerPrefix} · Page ${pageNumber} of ${totalPages}`
  // Disposals the engine could not match to any acquisition are assigned a zero
  // cost basis, so 100% of their proceeds becomes gain. That almost always means
  // the acquisition ledger is incomplete (e.g. RSU vests booked net instead of
  // gross); surface it loudly rather than letting an overstated gain pass silently.
  const unmatched = response.realized_events.filter((e) => e.rule_applied === "Unmatched")
  const unmatchedProceeds = unmatched.reduce(
    (sum, e) => sum + Number.parseFloat(e.proceeds),
    0,
  )
  // Allowances and a tax estimate only make sense for a whole UK tax year.
  const taxYear = filters.period.kind === "tax-year" ? filters.period.taxYear : null
  const taxEstimate = taxYear
    ? computeTaxEstimate(
        taxYear,
        Number.parseFloat(response.summary.net_gain_loss),
        response.realized_events,
        higherRate,
      )
    : null
  // Pool workings support THIS return's disposals, so only show pools for symbols
  // actually disposed in the period — not every holding still in the global pool.
  const disposedSymbols = new Set(response.realized_events.map((e) => e.symbol))
  const poolRows = response.pools.filter(
    (p) => Number.parseFloat(p.current_shares) > 0 && disposedSymbols.has(p.symbol),
  )
  return (
    <Document
      title={`Capital Gains Tax Report — ${periodLabel(filters.period)}`}
      author="fynance"
    >
      <Page size="A4" style={styles.page}>
        <Text style={styles.footer} fixed render={renderFooter} />
        <Text style={styles.h1}>Capital Gains Tax Report</Text>
        <Text style={styles.meta}>
          {periodLabel(filters.period)} · Generated {new Date(generatedAt).toLocaleString()}
        </Text>

        <Text style={styles.h2}>Summary</Text>
        <View style={styles.block}>
          <SummaryRow label="Number of disposals" value={String(response.realized_events.length)} />
          <SummaryRow label="Disposal proceeds" value={fmt(response.summary.total_proceeds, cur)} />
          <SummaryRow
            label="Allowable costs (including purchase price)"
            value={fmt(response.summary.total_allowable_costs, cur)}
          />
          <SummaryRow
            label="Gains in the year, before losses"
            value={fmt(response.summary.total_gains, cur)}
          />
          <SummaryRow label="Losses in the year" value={fmt(response.summary.total_losses, cur)} />
          <SummaryRow
            label="Net gain/loss in the year"
            value={fmt(response.summary.net_gain_loss, cur)}
            bold
          />
          {taxEstimate && (
            <>
              <SummaryRow
                label={`Annual Exempt Amount (${taxYear})`}
                value={`-${fmt(String(taxEstimate.aea), cur)}`}
              />
              <SummaryRow
                label="Taxable gain after allowance"
                value={fmt(String(taxEstimate.taxableGain), cur)}
                bold
              />
            </>
          )}
        </View>
        <Text style={styles.footnote}>
          {taxEstimate
            ? `Annual Exempt Amount applied for tax year ${taxYear}; brought-forward losses and any other disposals in the year are not included.`
            : "Figures are pre-relief; choose a tax year to apply the Annual Exempt Amount and estimate tax."}{" "}
          Foreign-currency disposals are converted to {cur} at the configured exchange rate.
        </Text>

        {unmatched.length > 0 && (
          <View style={styles.warning}>
            <Text style={styles.warningText}>
              ⚠ {unmatched.length} disposal{unmatched.length === 1 ? "" : "s"} (
              {fmt(String(unmatchedProceeds), cur)} of proceeds) could not be matched to
              any acquisition and were treated as 100% gain (zero cost basis). This
              usually means acquisition events (vests or buys) are missing or understated,
              so the gain above is overstated. Review the ledger before filing.
            </Text>
          </View>
        )}

        {taxEstimate && taxEstimate.bands.length > 0 && (
          <View style={styles.block}>
            <Text style={styles.h2}>Estimated Capital Gains Tax</Text>
            {taxEstimate.bands.map((b) => (
              <SummaryRow key={b.label} label={b.label} value={fmt(String(b.tax), cur)} />
            ))}
            <SummaryRow
              label="Estimated CGT due"
              value={fmt(String(taxEstimate.totalTax), cur)}
              bold
            />
            <Text style={styles.footnote}>
              Estimate only, not tax advice. Computed at the{" "}
              {higherRate ? "higher/additional" : "basic"} rate for the whole
              gain; a within-year basic/higher band split is not modelled. Assumes the full Annual
              Exempt Amount is available. Confirm with your accountant before filing.
            </Text>
          </View>
        )}

        {taxEstimate && taxEstimate.netGain > 0 && taxEstimate.bands.length === 0 && (
          <Text style={styles.footnote}>
            No Capital Gains Tax estimated for {taxYear}: the taxable gain falls within the Annual
            Exempt Amount.
          </Text>
        )}

        {response.symbol_summaries.length > 0 && (
          <>
            <Text style={styles.h2}>Per-symbol breakdown</Text>
            <View style={styles.tableHeader}>
              <Text style={{ flex: 1.5 }}>Symbol</Text>
              <Text style={{ flex: 1, textAlign: "right" }}>Proceeds</Text>
              <Text style={{ flex: 1, textAlign: "right" }}>Costs</Text>
              <Text style={{ flex: 1, textAlign: "right" }}>Net gain/loss</Text>
            </View>
            {response.symbol_summaries.map((s) => (
              <View key={s.symbol} style={styles.tableRow}>
                <Text style={{ flex: 1.5 }}>{s.symbol}</Text>
                <Text style={{ flex: 1, textAlign: "right" }}>{fmt(s.total_proceeds, cur)}</Text>
                <Text style={{ flex: 1, textAlign: "right" }}>
                  {fmt(s.total_allowable_costs, cur)}
                </Text>
                <Text style={{ flex: 1, textAlign: "right" }}>{fmt(s.net_gain_loss, cur)}</Text>
              </View>
            ))}
          </>
        )}
      </Page>

      {response.realized_events.length > 0 && (
        <Page size="A4" style={styles.page} wrap>
          <Text style={styles.footer} fixed render={renderFooter} />
          <Text style={styles.h1}>Capital Gains Disposal Summary</Text>
          <Text style={styles.meta}>
            One block per matched leg. Mirrors the SA108 supplementary workings page.
          </Text>
          {response.realized_events.map((e, idx) => (
            <DisposalBlock key={`${e.disposal_id}-${idx}`} event={e} currency={cur} />
          ))}
        </Page>
      )}

      {poolRows.length > 0 && (
        <Page size="A4" style={styles.page}>
          <Text style={styles.footer} fixed render={renderFooter} />
          <Text style={styles.h1}>S104 Pool Workings</Text>
          <Text style={styles.meta}>
            Average-cost pool for each symbol disposed in this period, supporting the
            costs above.
          </Text>
          <View style={styles.tableHeader}>
            <Text style={{ flex: 1.5 }}>Symbol</Text>
            <Text style={{ flex: 1, textAlign: "right" }}>Current shares</Text>
            <Text style={{ flex: 1.4, textAlign: "right" }}>Total allowable expenditure</Text>
            <Text style={{ flex: 1.2, textAlign: "right" }}>Avg cost / share</Text>
          </View>
          {poolRows.map((p) => (
            <View key={p.symbol} style={styles.tableRow}>
              <Text style={{ flex: 1.5 }}>{p.symbol}</Text>
              <Text style={{ flex: 1, textAlign: "right" }}>{fmtShares(p.current_shares)}</Text>
              <Text style={{ flex: 1.4, textAlign: "right" }}>
                {fmt(p.total_allowable_expenditure, cur)}
              </Text>
              <Text style={{ flex: 1.2, textAlign: "right" }}>
                {fmt(p.average_cost_per_share, cur)}
              </Text>
            </View>
          ))}
        </Page>
      )}
    </Document>
  )
}

function fmtShares(qty: string): string {
  const n = Number.parseFloat(qty)
  if (!Number.isFinite(n)) return "—"
  return n.toLocaleString("en-GB", { minimumFractionDigits: 0, maximumFractionDigits: 4 })
}

function DisposalBlock({
  event,
  currency,
}: {
  event: CgtRealizedEvent
  currency: string
}) {
  const acquisition = event.matches[0]?.acquisition_date ?? null
  return (
    <View style={styles.disposalBlock} wrap={false}>
      <Text style={styles.disposalHeader}>
        {event.symbol} — disposed {event.disposal_date.slice(0, 10)} · {event.rule_applied}
      </Text>
      <View style={styles.row}>
        <Text style={styles.label}>Date of acquisition</Text>
        <Text style={styles.value}>{acquisition ?? "Not matched"}</Text>
      </View>
      <View style={styles.row}>
        <Text style={styles.label}>Date of disposal</Text>
        <Text style={styles.value}>{event.disposal_date.slice(0, 10)}</Text>
      </View>
      <View style={styles.row}>
        <Text style={styles.label}>Quantity</Text>
        <Text style={styles.value}>{fmtShares(event.quantity)}</Text>
      </View>
      <View style={styles.row}>
        <Text style={styles.label}>Disposal proceeds</Text>
        <Text style={styles.value}>{fmt(event.proceeds, currency)}</Text>
      </View>
      <View style={styles.row}>
        <Text style={styles.label}>Acquisition cost</Text>
        <Text style={styles.value}>{fmt(event.cost_basis, currency)}</Text>
      </View>
      <View style={styles.row}>
        <Text style={[styles.label, styles.bold]}>Gain or (Loss)</Text>
        <Text style={[styles.value, styles.bold]}>{fmt(event.gain_loss, currency)}</Text>
      </View>
    </View>
  )
}

function SummaryRow({ label, value, bold = false }: { label: string; value: string; bold?: boolean }) {
  return (
    <View style={styles.row}>
      <Text style={[styles.label, bold ? styles.bold : {}]}>{label}</Text>
      <Text style={[styles.value, bold ? styles.bold : {}]}>{value}</Text>
    </View>
  )
}

// TEMPORARY hardcoded tax tables. These are UK statutory values that change with
// each Budget, so they are not expected to live in the frontend long-term: plan
// 23 §7.4/§7.5 moves the rates, Annual Exempt Amount, and band split into
// server-side, user-definable tax config. Until then, update these by hand when
// HMRC changes them.
// UK CGT Annual Exempt Amount by tax year (frozen at £3,000 from 2024-25).
const AEA_BY_TAX_YEAR: Record<string, number> = {
  "2018-19": 11700,
  "2019-20": 12000,
  "2020-21": 12300,
  "2021-22": 12300,
  "2022-23": 12300,
  "2023-24": 6000,
  "2024-25": 3000,
  "2025-26": 3000,
  "2026-27": 3000,
}

interface TaxBand {
  label: string
  taxable: number
  tax: number
}

interface TaxEstimate {
  aea: number
  netGain: number
  taxableGain: number
  bands: TaxBand[]
  totalTax: number
}


interface RateBand {
  start: string
  end?: string
  basic: number
  higher: number
}

// TEMPORARY hardcoded tax table (same as AEA_BY_TAX_YEAR above). UK statutory
// values that change with each Budget, so they are not expected to live in the
// frontend long-term: plan 23 §7.4/§7.5 moves the rates, Annual Exempt Amount,
// and band split into server-side, user-definable tax config. Until then, update
// these by hand when HMRC changes them.
// UK CGT rates on shares by disposal-date band. The Autumn Budget 2024 raised
// them mid-year (30 Oct 2024). `start` is required (inclusive) and `end` optional
// (exclusive; omitted = still current);
const CGT_RATE_BANDS: RateBand[] = [
  { start: "2016-04-06", end: "2024-10-30", basic: 0.1, higher: 0.2 },
  { start: "2024-10-30", basic: 0.18, higher: 0.24 },
]

function rateBandFor(date: string): RateBand | undefined {
  return CGT_RATE_BANDS.find((b) => date >= b.start && (b.end === undefined || date < b.end))
}

function fmtBandDate(iso: string): string {
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
  const [y, m, d] = iso.split("-")
  return `${Number(d)} ${months[Number(m) - 1]} ${y}`
}

function bandLabel(band: RateBand, rate: number, multiple: boolean): string {
  const pct = `${(rate * 100).toFixed(0)}%`
  if (!multiple) return `Taxable gains @ ${pct}`
  if (band.end) return `Gains before ${fmtBandDate(band.end)} @ ${pct}`
  return `Gains from ${fmtBandDate(band.start)} @ ${pct}`
}

// Estimated CGT on share gains. Each disposal is rated by its disposal-date band
// (so the 30 Oct 2024 mid-year change is just a band boundary, not a special
// case). `higherRate` picks basic vs higher within each band — we don't know the
// taxpayer's income, so a single band can't be split across both (see plan 23
// §7.4). The Annual Exempt Amount and any net-loss band relieve the highest-rate
// gains first, which minimises the charge and matches standard practice.
function computeTaxEstimate(
  taxYear: string,
  netGain: number,
  realized: CgtRealizedEvent[],
  higherRate: boolean,
): TaxEstimate | null {
  const aea = AEA_BY_TAX_YEAR[taxYear]
  if (aea === undefined) return null
  if (netGain <= 0) {
    return { aea, netGain, taxableGain: 0, bands: [], totalTax: 0 }
  }

  // Net each disposal's gain into its disposal-date rate band.
  const byBand = new Map<string, { band: RateBand; net: number }>()
  for (const e of realized) {
    const g = Number.parseFloat(e.gain_loss)
    if (!Number.isFinite(g)) continue
    const band = rateBandFor(e.disposal_date.slice(0, 10))
    if (!band) continue
    const entry = byBand.get(band.start) ?? { band, net: 0 }
    entry.net += g
    byBand.set(band.start, entry)
  }

  const rateOf = (b: RateBand) => (higherRate ? b.higher : b.basic)
  const gainBands = [...byBand.values()].filter((b) => b.net > 0)
  // A net-loss band plus the allowance come off the highest-rate gains first.
  const lossPool = [...byBand.values()].filter((b) => b.net < 0).reduce((s, b) => s + b.net, 0)
  let toDeduct = aea - lossPool
  gainBands.sort((a, b) => rateOf(b.band) - rateOf(a.band))

  const multiple = gainBands.length > 1
  const rated = gainBands.flatMap((gb) => {
    const rate = rateOf(gb.band)
    const deduct = Math.min(toDeduct, gb.net)
    toDeduct -= deduct
    const taxable = gb.net - deduct
    if (taxable <= 0) return []
    return [{ start: gb.band.start, label: bandLabel(gb.band, rate, multiple), taxable, tax: taxable * rate }]
  })
  rated.sort((a, b) => a.start.localeCompare(b.start))

  const bands: TaxBand[] = rated.map(({ label, taxable, tax }) => ({ label, taxable, tax }))
  return {
    aea,
    netGain,
    taxableGain: bands.reduce((s, b) => s + b.taxable, 0),
    bands,
    totalTax: bands.reduce((s, b) => s + b.tax, 0),
  }
}

const CURRENCY_SYMBOLS: Record<string, string> = {
  GBP: "£",
  USD: "$",
  EUR: "€",
  NGN: "₦",
}

function fmt(amount: string, currency: string): string {
  const n = Number.parseFloat(amount)
  if (!Number.isFinite(n)) return "—"
  const symbol = CURRENCY_SYMBOLS[currency] ?? `${currency} `
  const abs = Math.abs(n).toLocaleString("en-GB", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })
  return n < 0 ? `-${symbol}${abs}` : `${symbol}${abs}`
}
